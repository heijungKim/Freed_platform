const rnd = () => crypto.randomInt(0, 1_000_000) / 1_000_000;

/** 금액에 어울리는 가맹점 (범위에 맞는 후보 중 가중치 무작위, 없으면 가장 가까운 후보) */
export function pickMerchant(amount) {
  let cands = MERCHANTS.filter(([, min, max]) => amount >= min && amount <= max);
  if (!cands.length) {
    cands = [...MERCHANTS].sort((a, b) => Math.min(Math.abs(a[1] - amount), Math.abs(a[2] - amount))
      - Math.min(Math.abs(b[1] - amount), Math.abs(b[2] - amount))).slice(0, 5);
  }
  const total = cands.reduce((s, m) => s + m[3], 0);
  let x = rnd() * total;
  for (const m of cands) { x -= m[3]; if (x <= 0) return m[0]; }
  return cands[cands.length - 1][0];
}
